// Writes projects/dahc-ui/src/lib/core/icon/icon-registry.generated.ts from the SVG files in
// projects/dahc-ui/src/assets/icons, so icon names in code can never drift from the files.
// Run after adding or removing icons: npm run icons:registry
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = join(root, 'projects/dahc-ui/src/assets/icons');
const output = join(root, 'projects/dahc-ui/src/lib/core/icon/icon-registry.generated.ts');

/** Icon sets of DH Design System REF (Icons page 50:4272), by file-name prefix. */
const SETS = [
  { prefix: 'gov-', label: 'Government' },
  { prefix: 'service-', label: 'Services' },
  { prefix: 'view-', label: 'View' },
  { prefix: 'social-', label: 'Social media' },
];
const FUNCTIONAL = 'Functional';
/** Brand logos keep their own colours; every other icon takes the current text colour. */
const COLOURED_SUFFIX = '-brand';

const names = readdirSync(iconDir)
  .filter(file => file.endsWith('.svg'))
  .map(file => file.slice(0, -'.svg'.length))
  .sort();

const invalid = names.filter(name => !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name));
if (invalid.length > 0) {
  throw new Error(`Icon file names must be kebab-case: ${invalid.join(', ')}`);
}

const setOf = name => SETS.find(set => name.startsWith(set.prefix))?.label ?? FUNCTIONAL;
const groups = [FUNCTIONAL, ...SETS.map(set => set.label)].map(label => ({
  label,
  names: names.filter(name => setOf(name) === label),
}));
const coloured = names.filter(name => name.endsWith(COLOURED_SUFFIX));
const list = values => values.map(value => `  '${value}',`).join('\n');

writeFileSync(
  output,
  `// Generated by tools/generate-icon-registry.mjs from src/assets/icons. Do not edit by hand:
// add or remove SVG files, then run npm run icons:registry.

/** Every icon shipped with DAHC-UI (${names.length}). */
export const DAHC_ICON_NAMES = [
${list(names)}
] as const;

export type DahcIconName = (typeof DAHC_ICON_NAMES)[number];

export interface DahcIconSet {
  readonly label: string;
  readonly names: readonly DahcIconName[];
}

/** Icons grouped by DH icon set. */
export const DAHC_ICON_SETS: readonly DahcIconSet[] = [
${groups.map(group => `  {\n    label: '${group.label}',\n    names: [\n${group.names.map(name => `      '${name}',`).join('\n')}\n    ],\n  },`).join('\n')}
];

/** Brand logos rendered in their own colours instead of the current text colour. */
export const DAHC_COLOURED_ICONS: ReadonlySet<DahcIconName> = new Set<DahcIconName>([
${list(coloured)}
]);
`,
);

console.log(`icon registry: ${names.length} icons, ${coloured.length} coloured -> ${output}`);
